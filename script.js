let activeLang = localStorage.getItem("lang") || "tr";
let toastTimeout;

document.addEventListener("DOMContentLoaded", () => {
  setLanguage(activeLang, false);
  setupReveal();
  setupScroll();

  const langBtn = document.getElementById("langBtn");
  if (langBtn) {
    langBtn.addEventListener("click", () => {
      setLanguage(activeLang === "tr" ? "en" : "tr", true);
    });
  }

  const printBtn = document.getElementById("printBtn");
  if (printBtn) {
    printBtn.addEventListener("click", () => window.print());
  }

  const copyBtn = document.getElementById("copyEmailBtn");
  if (copyBtn) {
    copyBtn.addEventListener("click", () => {
      const email = copyBtn.dataset.email || "mecitaksu230@gmail.com";
      navigator.clipboard?.writeText(email);
      showToast(activeLang === "tr" ? "E-posta adresi kopyalandı" : "Email address copied");
    });
  }
});

function setLanguage(lang, animate) {
  activeLang = lang;
  document.documentElement.lang = lang;
  localStorage.setItem("lang", lang);

  const render = () => {
    const langBtn = document.getElementById("langBtn");
    if (langBtn) langBtn.textContent = lang === "tr" ? "EN" : "TR";

    document.querySelectorAll("[data-key]").forEach((el) => {
      const key = el.dataset.key;
      if (translations[lang][key]) {
        el.innerHTML = translations[lang][key];
      }
    });
  };

  if (animate) {
    document.body.classList.add("lang-switching");
    setTimeout(() => {
      render();
      document.body.classList.remove("lang-switching");
    }, 150);
  } else {
    render();
  }
}

function setupReveal() {
  const items = document.querySelectorAll(
    ".intro-section, .cv-section, .timeline-item, .skill-row, .project-item"
  );

  items.forEach((el, i) => {
    el.classList.add("reveal");
    el.style.transitionDelay = `${Math.min((i % 5) * 45, 180)}ms`;
  });

  if (!("IntersectionObserver" in window)) {
    items.forEach((el) => el.classList.add("is-visible"));
    return;
  }

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.08, rootMargin: "0px 0px -24px 0px" }
  );

  items.forEach((el) => observer.observe(el));
}

function setupScroll() {
  const header = document.getElementById("siteHeader");
  const progress = document.getElementById("scrollProgress");
  const sections = document.querySelectorAll("main section[id]");
  const navLinks = document.querySelectorAll(".site-nav a");

  const handleScroll = () => {
    const scrollTop = window.scrollY;
    const maxScroll = document.documentElement.scrollHeight - window.innerHeight;

    if (header) {
      header.classList.toggle("scrolled", scrollTop > 16);
    }

    if (progress) {
      const ratio = maxScroll > 0 ? Math.min((scrollTop / maxScroll) * 100, 100) : 0;
      progress.style.width = `${ratio}%`;
    }

    let current = "about";
    sections.forEach((section) => {
      if (scrollTop + 160 >= section.offsetTop) {
        current = section.id;
      }
    });

    navLinks.forEach((link) => {
      link.classList.toggle("active", link.getAttribute("href") === `#${current}`);
    });
  };

  window.addEventListener("scroll", handleScroll, { passive: true });
  handleScroll();
}

function showToast(text) {
  const toast = document.getElementById("toast");
  if (!toast) return;
  toast.textContent = text;
  toast.classList.add("show");
  clearTimeout(toastTimeout);
  toastTimeout = setTimeout(() => toast.classList.remove("show"), 2200);
}
